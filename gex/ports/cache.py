"""Порт кэша: «последнее известное значение + фоновое обновление».

Контракт фиксирует требования продукта: страница получает данные мгновенно, свежесть добирается
фоном, а вычисление одного ключа схлопывается между процессами (аудит 07: PC-02, PC-10).
Реализация — ``gex/adapters/cache/**`` (Redis + версионированный envelope + Redis-лок).
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any, Protocol, runtime_checkable

__all__ = ["CacheStatus", "CachedPayload", "CachePort", "SnapshotPort"]


class CacheStatus(str, Enum):
    """Как было получено значение (нужно для метрик и для заголовков ответа)."""

    HIT = "hit"          # свежее — отдали как есть
    STALE = "stale"      # отдали устаревшее + запустили фоновое обновление
    MISS = "miss"        # ничего не было — считали синхронно
    COMPUTING = "computing"  # отдали последнее, но пересчёт ещё идёт в другом процессе
    EXPIRED = "expired"  # значение есть, но старше ``stale_max`` — отдавать нельзя
    EMPTY = "empty"      # значения нет вовсе (ни в Redis, ни в памяти процесса)


@dataclass(frozen=True)
class CachedPayload:
    """Значение из кэша с метаданными.

    ``envelope`` обязан нести версию схемы: читатель отвергает чужую версию как miss, поэтому смена
    формата не требует ручной чистки Redis (аудит 07: PC-04, PC-14).
    """

    value: Any
    status: CacheStatus
    ts: float
    fresh: int
    stale_max: int
    version: int = 1
    etag: str | None = None
    computing: bool = False
    #: Возраст значения на момент чтения. Считает хранилище (у него есть и часы, и метка
    #: записи), а не читатель: иначе «возраст» считался бы от разных моментов времени
    #: в разных местах и метрика freshness разъезжалась бы с решением о статусе.
    age_s: float = 0.0


@runtime_checkable
class CachePort(Protocol):
    """Кэш значений с правилом свежести, заданным снаружи (см. ``gex.domain.freshness``)."""

    def get(
        self,
        key: str,
        *,
        fresh: int,
        stale_max: int,
        compute: "callable",
        max_wait_ms: int | None = None,
    ) -> CachedPayload:
        """Вернуть значение по SWR-логике; ``compute`` вызывается только при miss/фоне."""
        ...

    def invalidate(self, key: str) -> None:
        """Сбросить ключ (например, после ручного обновления данных)."""
        ...


@runtime_checkable
class SnapshotPort(Protocol):
    """Read-only кэш «последнего известного значения» — контракт «страница не ждёт провайдера».

    Почему отдельно от :class:`CachePort`
    -------------------------------------
    ``CachePort.get`` при промахе **считает** значение (это его смысл: SWR + single-flight).
    Страницам, вынесенным за пределы запроса, нужен противоположный контракт:

    * ``peek`` никогда не ходит во внешний источник и потому не может подвиснуть на нём;
    * значения кладёт фоновый пересчёт (задача воркера, прогрев, CLI) — его результат
      одинаков и для «тысячи браузеров», и для планировщика.

    Разделение этих двух обязанностей — не косметика: пока чтение и вычисление жили в одном
    вызове, промах кэша означал «пользователь ждёт yfinance столько, сколько понадобится»
    (широта рынка скачивает ~500 бумаг, страница не отвечала вовсе).
    """

    def peek(
        self,
        key: str,
        *,
        fresh: int,
        stale_max: int,
    ) -> "CachedPayload | None":
        """Прочитать последнее известное значение, ничего не вычисляя.

        ``None`` — значения нет нигде (ни в Redis, ни в памяти процесса): вызывающий обязан
        ответить «данные готовятся», а не считать синхронно. Иначе ``status``:
        ``HIT`` (свежее), ``STALE`` (годное устаревшее), ``EXPIRED`` (старше ``stale_max`` —
        значение отдаётся для диагностики, но пользователю показывать его нельзя).
        """
        ...

    def write(self, key: str, value: Any, *, fresh: int, source: str = "") -> None:
        """Положить значение (единственный путь записи — фоновое обновление)."""
        ...

    def invalidate(self, key: str) -> None:
        """Забыть значение (ручной сброс, смена формы значения)."""
        ...
