"""Канонический словарь таймфреймов приложения (кольцо: domain).

Почему это отдельный модуль домена, а не константа в ``adapters/providers/catalog``
----------------------------------------------------------------------------------
Таймфрейм — это **понятие предметной области**, а не деталь провайдера: набор
``("1h", "2h", "4h", "1d")`` и правило «2h/4h получаются ресемплингом из 1h» одинаковы
для всех площадок, а карты интервалов (``"60"`` у Bybit, ``"60"`` у ISS, ``24`` у yfinance)
— уже деталь конкретного источника, и они остаются в каталоге.

Раньше константа жила в ``gex/adapters/providers/catalog.py``, а ``gex/domain/ta.py``
импортировала её оттуда — это нарушение правила R1 (домен не зависит от внешних колец).
Оно появилось ещё до раскладки плоских файлов, но стало **видимым** только после неё:
до переноса ``ta.py`` лежал в корне ``gex/`` и под R1 не попадал, поэтому «0 нарушений»
ничего не говорило о фактическом долге (см. ``docs/clean-arch-refactor-plan.md`` §6.9).

Каталог реэкспортирует отсюда (:data:`CANONICAL_TIMEFRAMES`), поэтому вызывающие
не меняются: единственный источник значения — этот модуль.
"""

from __future__ import annotations

#: Канонические таймфреймы приложения. Порядок значим: он же порядок вывода и построения
#: графиков, поэтому именно ``tuple``, а не ``set``.
CANONICAL_TIMEFRAMES: tuple[str, ...] = ("1h", "2h", "4h", "1d")

__all__ = ["CANONICAL_TIMEFRAMES"]
